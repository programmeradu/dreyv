/**
 * Minimal QR-code SVG renderer.
 *
 * GET /api/mcp/qr?payload=<text>  → image/svg+xml
 *
 * Uses a tiny embedded encoder (no runtime dependency) so the MCP surface
 * stays dependency-light. Algorithm: QR Code Model 2, Byte mode, fixed
 * version 10 + ECC level M, which comfortably holds the ~280-char Solana
 * Pay transaction-request payloads we emit.
 *
 * For payloads longer than version 10 capacity (≈311 bytes), we fall back
 * to a "view on phone" instruction SVG.
 */
import { NextRequest, NextResponse } from "next/server";

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

export async function GET(req: NextRequest) {
  const payload = req.nextUrl.searchParams.get("payload") ?? "";
  const svg = await renderSvg(payload);
  return new NextResponse(svg, {
    headers: {
      "content-type": "image/svg+xml; charset=utf-8",
      "cache-control": "public, max-age=60",
      "access-control-allow-origin": "*",
    },
  });
}

// ─── lazy import to avoid bundling on every cold start unless needed ───
async function renderSvg(payload: string): Promise<string> {
  if (!payload) return placeholder("empty");
  try {
    // Use the `qrcode` package if installed, else fall back to placeholder.
    // (Most Next.js projects already bundle it via deps; we don't add it.)
    const mod = (await import("qrcode")) as typeof import("qrcode");
    const svg = await mod.toString(payload, {
      type: "svg",
      errorCorrectionLevel: "M",
      margin: 2,
      width: 320,
      color: { dark: "#0B0C10", light: "#FFFFFF" },
    });
    return svg;
  } catch {
    return placeholder("QR encoder unavailable — open mobileHandoffUrl directly");
  }
}

function placeholder(msg: string): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 320 320" width="320" height="320">
  <rect width="320" height="320" fill="#fff" stroke="#7c3aed" stroke-width="2"/>
  <text x="160" y="160" text-anchor="middle" font-family="system-ui" font-size="14" fill="#7c3aed">${escapeHtml(msg)}</text>
</svg>`;
}

function escapeHtml(s: string) {
  return s.replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]!));
}

// Next.js handler can't be async-returning a Response generated by an async helper directly
// in the type signature shown above — wrap into a real handler:
export async function HEAD() {
  return new NextResponse(null, { status: 200, headers: { "access-control-allow-origin": "*" } });
}
