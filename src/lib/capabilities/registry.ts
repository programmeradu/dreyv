export type SideEffect = "read" | "simulate" | "write";
export type Pillar = "identity" | "portfolio" | "market" | "execution" | "forensics" | "tax" | "foresight" | "agentic" | "economy" | "reasoning" | "knowledge" | "governance" | "defi" | "developer" | "safety" | "compliance" | "notifications" | "audit" | "teams" | "billing" | "privacy" | "storage" | "search" | "status" | "jobs" | "exports" | "tags" | "flags" | "inbox" | "insights" | "marketplace" | "sla" | "contracts" | "observability" | "limits" | "residency" | "digests" | "workflows" | "entitlements";
export type Status = "stable" | "preview";

export interface PublicCapability<TInput extends z.ZodTypeAny = z.ZodTypeAny> {
  /** dot.path id, also the REST path: /api/v1/{id.replace(/\./g, '/')} */
  id: string;
  /** snake_case alias used as the MCP tool name. */
  mcpName: string;
  pillar: Pillar;
  scope: ApiScope;
  sideEffects: SideEffect;
  status: Status;
  title: string;
  description: string;
  inputSchema: TInput;
  handler: (input: z.infer<TInput>, ctx: CapabilityRunContext) => Promise<unknown>;
  /** Credits charged per successful call. 0 = free in Phase 1. */
  cost?: number;
}

export interface CapabilityRunContext {
  userId: string;
  keyId: string;
  origin: string;
  transport: "rest" | "mcp";
}

